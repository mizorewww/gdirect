#!/usr/bin/env python3
"""Generate the tap formula and desktop cask from the verified release checksums."""
import argparse
import pathlib
import re

parser = argparse.ArgumentParser()
parser.add_argument('--version', required=True)
parser.add_argument('--checksums', type=pathlib.Path, required=True)
parser.add_argument('--output', type=pathlib.Path, default=pathlib.Path('Formula/gdirect.rb'))
parser.add_argument('--cask', type=pathlib.Path, default=pathlib.Path('Casks/gdirect-desktop.rb'))
args = parser.parse_args()
assert re.fullmatch(r'\d+\.\d+\.\d+', args.version), 'Expected a stable semantic version'
checksums = {}
for line in args.checksums.read_text().splitlines():
    digest, filename = line.split()
    assert re.fullmatch(r'[0-9a-f]{64}', digest)
    checksums[filename.removeprefix('./')] = digest

def source(target, indent):
    name = f'gdirect-{args.version}-{target}.tar.gz'
    return f'{indent}url "https://github.com/mizorewww/gdirect/releases/download/v{args.version}/{name}"\n{indent}sha256 "{checksums[name]}"'

formula = f'''# Generated by scripts/update-homebrew.py from release SHA256SUMS.
class Gdirect < Formula
  desc "Browse, download, upload and mount Google Drive"
  homepage "https://github.com/mizorewww/gdirect"
  version "{args.version}"
  license "GPL-2.0-or-later"

  on_macos do
    depends_on macos: :sequoia
    on_arm do
{source('aarch64-apple-darwin', '      ')}
    end
    on_intel do
{source('x86_64-apple-darwin', '      ')}
    end
  end

  on_linux do
    depends_on arch: :x86_64
    on_intel do
{source('x86_64-unknown-linux-gnu', '      ')}
    end
  end

  def install
    libexec.install "gdirect"
    bin.write_exec_script libexec/"gdirect"
    doc.install "README.md", "README.zh-CN.md", "BUILD-INFO.json"
    doc.install "docs" if File.directory?("docs")
    (share/"licenses/gdirect").install Dir["*LICENSE*"]
  end

  def caveats
    <<~EOS
      Next: create a Google OAuth client (one time), then sign in:
        https://github.com/mizorewww/gdirect/blob/main/docs/configuration/README.md
        gdirect login --client-secret /path/to/client_secret.json
      Mounting also needs rclone (and your distro's fuse3 package on Linux):
        brew install rclone
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/gdirect --version")
    assert_match "upload", shell_output("#{{bin}}/gdirect --help")
  end
end
'''
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(formula)
print(f'Updated {args.output} to {args.version}')

# The desktop client's macOS app, from the release's version-less zips.
cask = f'''# Generated by scripts/update-homebrew.py from release SHA256SUMS.
cask "gdirect-desktop" do
  arch arm: "arm64", intel: "x64"

  version "{args.version}"
  sha256 arm:   "{checksums['gdirect-desktop-macos-arm64.zip']}",
         intel: "{checksums['gdirect-desktop-macos-x64.zip']}"

  url "https://github.com/mizorewww/gdirect/releases/download/v#{{version}}/gdirect-desktop-macos-#{{arch}}.zip"
  name "gdirect"
  desc "Desktop client for browsing, transferring and mounting Google Drive"
  homepage "https://github.com/mizorewww/gdirect"

  depends_on macos: :sequoia

  app "gdirect.app"

  caveats <<~EOS
    gdirect is not notarized. If macOS refuses to open it, allow it once under
    System Settings > Privacy & Security > Open Anyway.
  EOS
end
'''
args.cask.parent.mkdir(parents=True, exist_ok=True)
args.cask.write_text(cask)
print(f'Updated {args.cask} to {args.version}')
